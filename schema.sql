CREATE TABLE IF NOT EXISTS users (
  email VARCHAR(190) NOT NULL PRIMARY KEY,
  nome VARCHAR(80) NOT NULL,
  pass_hash VARCHAR(255) NOT NULL,
  criado BIGINT NOT NULL,
  pw_at BIGINT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS resets (
  token_hash CHAR(64) NOT NULL PRIMARY KEY,
  email VARCHAR(190) NOT NULL,
  exp INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ent (
  email VARCHAR(190) NOT NULL PRIMARY KEY,
  ebook TINYINT NOT NULL DEFAULT 0,
  trimestral TINYINT NOT NULL DEFAULT 0,
  ate BIGINT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS prog (
  email VARCHAR(190) NOT NULL PRIMARY KEY,
  nivel TEXT NULL,
  sem TEXT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS notas (
  email VARCHAR(190) NOT NULL PRIMARY KEY,
  txt VARCHAR(500) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS pago (
  sid VARCHAR(190) NOT NULL PRIMARY KEY,
  criado INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS rl (
  k VARCHAR(190) NOT NULL PRIMARY KEY,
  n INT NOT NULL,
  exp INT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
